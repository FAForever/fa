"""Generates units/unit-names.md, a table of unit IDs and names, from units/*/*_unit.bp.

Run from the repository root: python scripts/generate-unit-names.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "units" / "unit-names.md"

TECH = {
    "TECH1": "T1",
    "TECH2": "T2",
    "TECH3": "T3",
    "EXPERIMENTAL": "Experimental",
}

# top-level fields are indented by 4 spaces, fields of General by 8
DESCRIPTION = re.compile(r'^ {4}Description = ["\'](.*)["\'],', re.M)
UNIT_NAME = re.compile(r'^ {8}UnitName = ["\'](.*)["\'],', re.M)
FACTION = re.compile(r'^ {8}FactionName = ["\'](.*)["\'],', re.M)
CATEGORIES = re.compile(r'^ {4}Categories = \{(.*?)^ {4}\}', re.M | re.S)
LOC = re.compile(r"^<LOC [^>]*>")


def field(pattern, text):
    match = pattern.search(text)
    return LOC.sub("", match.group(1)).replace("\\", "").strip() if match else ""


def entry(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    categories = CATEGORIES.search(text)
    categories = re.findall(r'["\'](\w+)["\']', categories.group(1)) if categories else []
    tech = next((TECH[c] for c in categories if c in TECH), "")
    description = field(DESCRIPTION, text)
    if not description:
        return None
    if tech and not description.startswith(tech):
        description = f"{tech} {description}"
    name = field(UNIT_NAME, text)
    title = f"{name}: {description}" if name and name != description else description
    unit_id = path.name[: -len("_unit.bp")].upper()
    return unit_id, title, field(FACTION, text)


def main():
    rows = sorted(filter(None, map(entry, ROOT.glob("units/*/*_unit.bp"))))
    lines = [
        "# Unit names",
        "",
        "Generated by [scripts/generate-unit-names.py](../scripts/generate-unit-names.py) from the `_unit.bp` files. Don't edit it by hand; rerun the script after adding, removing or renaming a unit.",
        "",
        "Titles follow the `<UnitName>: <Tech> <Description>` format of [balance snippets](../docs/development-changelog/balance-snippet.md). Units without a `UnitName`, such as most structures, have only the tech and description, so search by faction too. Units without a `Description` (effects and dummies) are left out. The blueprint is `units/<ID>/<ID>_unit.bp`.",
        "",
        "| ID | Title | Faction |",
        "|---|---|---|",
    ]
    lines += [f"| {unit_id} | {title.replace('|', '/')} | {faction} |" for unit_id, title, faction in rows]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(rows)} units to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
